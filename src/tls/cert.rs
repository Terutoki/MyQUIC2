use anyhow::{Context, Result};

// ---------------- Self-signed cert (TLS1.3 + AES-128-GCM fastest) ----------------
/// Generate self-signed cert for `san`, save PEM files, return (cert_pem, key_pem).
/// Algorithm: Ed25519 (fastest sign/verify, smallest cert). Validity: 500 years,
/// backdated 7 days so devices without a battery clock (NTP not yet synced at
/// first boot) never fail with "certificate not valid yet".
///
/// The **key** is written private (`0600` on Unix): clients pin this exact
/// certificate as their only trust root, so anyone who can read the key can
/// impersonate the server to every pinned client. `std::fs::write` would create
/// it `0644` under the usual umask and silently expose the tunnel's identity to
/// any local user. The cert itself is public and stays readable.
pub fn gen_self_signed_files(san: &str, cert_path: &str, key_path: &str) -> Result<()> {
    let mut params = rcgen::CertificateParams::new(vec![san.to_string()])?;
    let now = ::time::OffsetDateTime::now_utc();
    params.not_before = now - ::time::Duration::days(7);
    params.not_after = now + ::time::Duration::days(500 * 365);
    let key_pair = rcgen::KeyPair::generate_for(&rcgen::PKCS_ED25519)?;
    let cert = params.self_signed(&key_pair)?;
    std::fs::write(cert_path, cert.pem()).context("write cert")?;
    write_private_key(key_path, key_pair.serialize_pem().as_bytes())?;
    Ok(())
}

/// Write the server's private key with `0600` permissions (Unix).
///
/// `OpenOptionsExt::mode` only *requests* the mode when the file is created
/// (`create(true)` + `truncate(true)` keeps the existing file's mode on a
/// rewrite), so the explicit `set_permissions` afterwards also tightens a key
/// file that already existed with looser permissions — e.g. one generated by an
/// older build of this binary.
fn write_private_key(key_path: &str, pem: &[u8]) -> Result<()> {
    #[cfg(unix)]
    {
        use std::io::Write as _;
        use std::os::unix::fs::{OpenOptionsExt as _, PermissionsExt as _};
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(key_path)
            .with_context(|| format!("create {key_path}"))?;
        file.write_all(pem)
            .with_context(|| format!("write {key_path}"))?;
        // `mode` applies only at creation; force it for a pre-existing file.
        std::fs::set_permissions(key_path, std::fs::Permissions::from_mode(0o600))
            .with_context(|| format!("chmod 0600 {key_path}"))?;
        Ok(())
    }
    #[cfg(not(unix))]
    {
        std::fs::write(key_path, pem).context("write key")?;
        Ok(())
    }
}

pub fn load_cert_der(pem_path: &str) -> Result<rustls::pki_types::CertificateDer<'static>> {
    let mut r = std::io::BufReader::new(std::fs::File::open(pem_path)?);
    let v: Vec<_> = rustls_pemfile::certs(&mut r).collect::<Result<Vec<_>, _>>()?;
    v.into_iter().next().context("no cert in file")
}

pub fn load_key_der(pem_path: &str) -> Result<rustls::pki_types::PrivateKeyDer<'static>> {
    let mut r = std::io::BufReader::new(std::fs::File::open(pem_path)?);
    rustls_pemfile::private_key(&mut r)?.context("no key in file")
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt as _;

    /// Temp dir unique to this process+test invocation (no dev-dependency for
    /// this): the key-permission test writes real files and must not collide
    /// with a concurrent run.
    fn temp_dir(tag: &str) -> std::path::PathBuf {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .expect("clock")
            .as_nanos();
        std::env::temp_dir().join(format!("myquic2-cert-{tag}-{}-{nanos}", std::process::id()))
    }

    /// SEC-1: the generated private key must not be readable by other users.
    /// Clients pin the certificate as their only root, so a world-readable key
    /// is a full server-impersonation primitive for any local account.
    #[test]
    fn generated_private_key_is_0600() {
        let dir = temp_dir("perms");
        std::fs::create_dir_all(&dir).expect("temp dir");
        let cert = dir.join("cert.pem");
        let key = dir.join("key.pem");
        gen_self_signed_files(
            "perm-test.invalid",
            cert.to_str().expect("utf8 cert path"),
            key.to_str().expect("utf8 key path"),
        )
        .expect("generate cert/key");

        let mode = std::fs::metadata(&key)
            .expect("key metadata")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(mode, 0o600, "private key mode must be 0600, got {mode:o}");
        // The certificate is public and stays readable.
        let cert_mode = std::fs::metadata(&cert)
            .expect("cert metadata")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(cert_mode & 0o400, 0o400, "cert must stay readable");

        // A pre-existing loose key file is tightened on rewrite.
        std::fs::set_permissions(&key, std::fs::Permissions::from_mode(0o644))
            .expect("loosen for the test");
        gen_self_signed_files(
            "perm-test.invalid",
            cert.to_str().expect("utf8 cert path"),
            key.to_str().expect("utf8 key path"),
        )
        .expect("regenerate over existing files");
        let mode = std::fs::metadata(&key)
            .expect("key metadata")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(mode, 0o600, "an existing key is tightened to 0600");

        // Both files are valid PEM the loaders accept (the mode change must not
        // have corrupted the content).
        load_cert_der(cert.to_str().expect("utf8 cert path")).expect("cert parses");
        load_key_der(key.to_str().expect("utf8 key path")).expect("key parses");

        let _ = std::fs::remove_dir_all(&dir);
    }
}
